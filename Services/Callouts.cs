    /// <summary>The Russian label for a place zone on the radar.</summary>
    public static string RadarName(string mapId, PlaceMark place) =>
        RadarNames.GetValueOrDefault(mapId)?.GetValueOrDefault(place.Key)
        ?? CommonRadarNames.GetValueOrDefault(place.Key)
        ?? place.Ru;
    /// <summary>The English label for a place zone: the handbook's callout (Window, not Sniper's Nest), or the game's name if it has none.</summary>
    public static string RadarEnName(string mapId, PlaceMark place) => ForPlace(mapId, place.Key)?.En ?? place.En;

    static string PlaceKey(string mapId, string name)
    {
        var k = new string(name.Where(char.IsLetter).ToArray()).ToLowerInvariant();
        k = PlaceAliases.GetValueOrDefault(k, k);
        k = MapPlaceAliases.GetValueOrDefault(mapId)?.GetValueOrDefault(k) ?? k;
        return k.Length > 4 && k.EndsWith('s') ? k[..^1] : k;
    }

    /// <summary>The community callout that matches a Valve place zone, if the handbook has one.</summary>
    public static Callout? ForPlace(string mapId, string placeKey) =>
        All.FirstOrDefault(c => c.Map == mapId && PlaceKey(mapId, c.En) == PlaceKey(mapId, placeKey));

    /// <summary>Whether a callout points at this place zone.</summary>
    public static bool SamePlace(Callout c, string placeKey) => PlaceKey(c.Map, c.En) == PlaceKey(c.Map, placeKey);
